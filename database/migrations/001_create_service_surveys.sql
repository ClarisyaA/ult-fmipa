CREATE TABLE IF NOT EXISTS `ult_service_surveys` (
  `ID` BIGINT NOT NULL AUTO_INCREMENT,
  `SERVICE_SLUG` VARCHAR(100) NOT NULL,
  `SOURCE_TABLE` VARCHAR(100) NOT NULL,
  `REQUEST_ID` BIGINT NOT NULL,
  `NPM` VARCHAR(50) NOT NULL,
  `RATING_TANGIBILITY` INT NULL,
  `RATING_RELIABILITY` INT NULL,
  `RATING_RESPONSIVENESS` INT NULL,
  `RATING_ASSURANCE` INT NULL,
  `RATING_EMPATHY` INT NULL,
  `OVERALL_RATING` INT NOT NULL,
  `COMMENT` TEXT NULL,
  `CREATED_AT` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `UPDATED_AT` DATETIME(3) NULL,
  PRIMARY KEY (`ID`),
  UNIQUE KEY `uniq_ult_service_surveys_request_npm` (
    `SERVICE_SLUG`,
    `SOURCE_TABLE`,
    `REQUEST_ID`,
    `NPM`
  ),
  KEY `idx_ult_service_surveys_service` (`SERVICE_SLUG`, `SOURCE_TABLE`),
  KEY `idx_ult_service_surveys_created_at` (`CREATED_AT`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
