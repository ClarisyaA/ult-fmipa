CREATE TABLE IF NOT EXISTS `ult_service_suggestions` (
  `ID` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `NAMA` VARCHAR(200) NOT NULL,
  `NPM` VARCHAR(50) NOT NULL,
  `LAYANAN_DIAJUKAN` VARCHAR(200) NOT NULL,
  `DETAIL_LAYANAN` TEXT NOT NULL,
  `SARAN_PENINGKATAN` TEXT NULL,
  `STATUS` VARCHAR(30) NOT NULL DEFAULT 'new',
  `ADMIN_NOTE` TEXT NULL,
  `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `UPDATED_AT` DATETIME NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`ID`),
  KEY `idx_ult_service_suggestions_npm` (`NPM`),
  KEY `idx_ult_service_suggestions_status` (`STATUS`),
  KEY `idx_ult_service_suggestions_created_at` (`CREATED_AT`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
