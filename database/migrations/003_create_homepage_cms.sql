CREATE TABLE IF NOT EXISTS `ult_home_activities` (
  `ID` BIGINT NOT NULL AUTO_INCREMENT,
  `TITLE` VARCHAR(150) NOT NULL,
  `EYEBROW` VARCHAR(80) NULL,
  `DESCRIPTION` TEXT NOT NULL,
  `IMAGE_PATH` VARCHAR(500) NULL,
  `IMAGE_ORIGINAL_NAME` VARCHAR(255) NULL,
  `IMAGE_STORED_NAME` VARCHAR(255) NULL,
  `IMAGE_MIME_TYPE` VARCHAR(100) NULL,
  `IMAGE_SIZE_BYTES` INT NULL,
  `IMAGE_ALT` VARCHAR(150) NULL,
  `IMAGE_FIT` VARCHAR(20) NOT NULL DEFAULT 'cover',
  `IS_ACTIVE` TINYINT(1) NOT NULL DEFAULT 1,
  `SORT_ORDER` INT NOT NULL DEFAULT 0,
  `CREATED_AT` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `UPDATED_AT` DATETIME(3) NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP(3),
  `CREATED_BY` VARCHAR(100) NULL,
  `UPDATED_BY` VARCHAR(100) NULL,
  PRIMARY KEY (`ID`),
  INDEX `idx_ult_home_activities_active_sort` (`IS_ACTIVE`, `SORT_ORDER`, `CREATED_AT`),
  INDEX `idx_ult_home_activities_sort` (`SORT_ORDER`, `CREATED_AT`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `ult_home_links` (
  `ID` BIGINT NOT NULL AUTO_INCREMENT,
  `LINK_KEY` VARCHAR(100) NOT NULL,
  `LABEL` VARCHAR(150) NOT NULL,
  `URL` VARCHAR(500) NOT NULL,
  `IS_ACTIVE` TINYINT(1) NOT NULL DEFAULT 1,
  `CREATED_AT` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `UPDATED_AT` DATETIME(3) NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP(3),
  `UPDATED_BY` VARCHAR(100) NULL,
  PRIMARY KEY (`ID`),
  UNIQUE KEY `uniq_ult_home_links_key` (`LINK_KEY`),
  INDEX `idx_ult_home_links_active` (`IS_ACTIVE`, `LINK_KEY`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

