CREATE TABLE IF NOT EXISTS `ult_information_posts` (
  `ID` BIGINT NOT NULL AUTO_INCREMENT,
  `TITLE` VARCHAR(200) NOT NULL,
  `SLUG` VARCHAR(220) NOT NULL,
  `CATEGORY` VARCHAR(100) NULL,
  `SUMMARY` VARCHAR(300) NULL,
  `CONTENT` TEXT NOT NULL,
  `STATUS` ENUM('draft', 'published', 'archived') NOT NULL DEFAULT 'draft',
  `IS_ACTIVE` TINYINT(1) NOT NULL DEFAULT 1,
  `IS_FEATURED` TINYINT(1) NOT NULL DEFAULT 0,
  `DISPLAY_START_AT` DATETIME(3) NULL,
  `DISPLAY_END_AT` DATETIME(3) NULL,
  `PUBLISHED_AT` DATETIME(3) NULL,
  `CREATED_BY` VARCHAR(100) NULL,
  `UPDATED_BY` VARCHAR(100) NULL,
  `CREATED_AT` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `UPDATED_AT` DATETIME(3) NULL,
  PRIMARY KEY (`ID`),
  UNIQUE KEY `uniq_ult_information_posts_slug` (`SLUG`),
  INDEX `idx_ult_information_posts_status_published` (`STATUS`, `PUBLISHED_AT`),
  INDEX `idx_ult_information_posts_category` (`CATEGORY`),
  INDEX `idx_ult_information_posts_visibility` (`STATUS`, `IS_ACTIVE`, `DISPLAY_START_AT`, `DISPLAY_END_AT`),
  INDEX `idx_ult_information_posts_featured` (`IS_FEATURED`, `PUBLISHED_AT`, `CREATED_AT`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `ult_information_post_images` (
  `ID` BIGINT NOT NULL AUTO_INCREMENT,
  `POST_ID` BIGINT NOT NULL,
  `ORIGINAL_NAME` VARCHAR(255) NOT NULL,
  `STORED_NAME` VARCHAR(255) NOT NULL,
  `MIME_TYPE` VARCHAR(100) NOT NULL,
  `SIZE_BYTES` INT NOT NULL,
  `STORAGE_PATH` VARCHAR(500) NOT NULL,
  `ALT_TEXT` VARCHAR(200) NULL,
  `IMAGE_FIT` VARCHAR(20) NOT NULL DEFAULT 'cover',
  `SORT_ORDER` INT NOT NULL DEFAULT 0,
  `IS_COVER` TINYINT(1) NOT NULL DEFAULT 0,
  `CREATED_AT` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`ID`),
  INDEX `idx_ult_information_post_images_post` (`POST_ID`),
  INDEX `idx_ult_information_post_images_cover` (`POST_ID`, `IS_COVER`),
  INDEX `idx_ult_information_post_images_sort` (`POST_ID`, `SORT_ORDER`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
